"""
    CuDensityMat

Julia bindings for NVIDIA's cuDensityMat library — high-performance density matrix
simulation for analog quantum dynamics (Lindblad master equation, time-dependent
Hamiltonians, backward differentiation/gradients).

Part of the CuQuantum.jl package. Targets cuDensityMat 0.7 (cuQuantum 26.9).
"""
module CuDensityMat

using CUDACore
using CUDACore: CuPtr, PtrOrCuPtr, unsafe_free!, HandleCache
using CUDACore: CUstream, cudaDataType, libraryPropertyType
using CUDACore: retry_reclaim, initialize_context
using CUDACore: @checked, @gcsafe_ccall
using CUDACore: R_32F, R_64F, C_32F, C_64F, cuDoubleComplex

using CEnum: @cenum

const _local_toolkit = CUDACore.local_toolkit
if _local_toolkit
    using CUDA_Runtime_Discovery
else
    import cuQuantum_jll
end

# Library handle — set in __init__
libcudensitymat = nothing

"""
Oldest cuDensityMat release whose ABI the generated bindings match
(`cudensitymatCreateOperatorAction` gained `scopeKind`/`approachKind` in 0.7).
"""
const MIN_LIBRARY_VERSION = v"0.7.0"

const cudaDataType_t = cudaDataType

# Low-level C API (generated by gen/generate.jl from the cuQuantum_jll header):
# enums, opaque handles, callback structs, and @checked ccall wrappers.
include("libcudensitymat.jl")

# Error handling
include("error.jl")

# Convenience wrappers
include("wrappers.jl")

# Deferred, ordered destruction of GC-reclaimed library objects
include("lifetime.jl")

# WorkStream (high-level handle + workspace + stream + communicator)
include("workspace.jl")

# Quantum states (DensePureState, DenseMixedState)
include("state.jl")

# Operators (ElementaryOperator, OperatorTerm, Operator, OperatorAction)
include("operators.jl")

# Callbacks (time-dependent scalar/tensor coefficients, CPU and GPU)
include("callbacks.jl")

# Expectation values
include("expectation.jl")

# Eigenspectrum solver
include("spectrum.jl")

# --- Handle management ---

# Per-context handle cache following CUDA.jl pattern
const _handle_cache = HandleCache{CUDACore.CuContext,cudensitymatHandle_t}(
    (_) -> create(),
    (_, h) -> destroy(h),
)

"""
    handle() -> cudensitymatHandle_t

Get a cuDensityMat library handle for the current CUDA context.
Handles are cached per-context and reused.
"""
function handle()
    ctx = CUDACore.context()
    return pop!(_handle_cache, ctx)
end

"""
    release_handle(h::cudensitymatHandle_t)

Return a handle to the cache for reuse.
"""
function release_handle(h::cudensitymatHandle_t)
    ctx = CUDACore.context()
    push!(_handle_cache, ctx, h)
end

"""
    functional() -> Bool

Whether the cuDensityMat library was found, matches the binding ABI
(version ≥ [`MIN_LIBRARY_VERSION`](@ref)), and a CUDA device is available.
Note that the library additionally requires compute capability ≥ 7.5.
"""
functional() = _functional[]
const _functional = Ref(false)

function __init__()
    precompiling = ccall(:jl_generating_output, Cint, ()) != 0

    # C-callable callback trampolines need no GPU
    _init_callback_wrappers!()

    # Find the library. This does not need a functional GPU, so that version and
    # binding checks work on any machine that can load the library.
    global libcudensitymat
    if _local_toolkit
        local dirs = CUDA_Runtime_Discovery.find_toolkit()
        local path =
            CUDA_Runtime_Discovery.get_library(dirs, "cudensitymat"; optional = true)
        if path === nothing
            precompiling || @error "cuDensityMat is not available on your system"
            return
        end
        libcudensitymat = path
    else
        if !cuQuantum_jll.is_available()
            precompiling ||
                !CUDACore.functional() ||
                @error "cuQuantum is not available for your platform ($(Base.BinaryPlatforms.triplet(cuQuantum_jll.host_platform)))"
            return
        end
        libcudensitymat = cuQuantum_jll.libcudensitymat
    end

    if version() < MIN_LIBRARY_VERSION
        precompiling ||
            @error "cuDensityMat $(version()) is older than $MIN_LIBRARY_VERSION, whose ABI these bindings target"
        return
    end

    _functional[] = CUDACore.functional()
end

end # module CuDensityMat
